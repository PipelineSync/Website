"""Build a self-hosted Font Awesome subset containing only the icons the site uses.

Usage:
  npm pack @fortawesome/fontawesome-free@6.5.2 && tar -xzf fortawesome-fontawesome-free-6.5.2.tgz
  pip install fonttools brotli
  python3 tools/build-icon-subset.py path/to/package

Scans src/ and assets/js/ for `fa-*` classes, writes assets/vendor/fa/icons.css and subset WOFF2 fonts.
Re-run after adding a new icon to the markup.
"""
import re
import sys
from pathlib import Path

from fontTools import subset

root = Path(__file__).resolve().parent.parent
pkg = Path(sys.argv[1]) if len(sys.argv) > 1 else None
if not pkg or not (pkg / 'css' / 'all.css').exists():
    sys.exit(__doc__)

out = root / 'assets' / 'vendor' / 'fa'
out.mkdir(parents=True, exist_ok=True)

used = set()
for f in list((root / 'src').rglob('*.njk')) + list((root / 'assets' / 'js').rglob('*.js')):
    used |= set(re.findall(r'\bfa-[a-z0-9-]+', f.read_text(encoding='utf8')))
used -= {'fa-solid', 'fa-brands', 'fa-regular'}
# Glyphs referenced from CSS `content:` (e.g. the ROI calculator button) must be listed here.
extra_codepoints = {'f1ec'}  # fa-calculator

css = (pkg / 'css' / 'all.css').read_text(encoding='utf8')
icon_map = {}
for selectors, body in re.findall(r'([^{}]+)\{([^{}]*)\}', css):
    m = re.search(r'content:\s*"\\([0-9a-f]+)"', body)
    if not m:
        continue
    for sel in selectors.split(','):
        name = re.match(r'\s*\.(fa-[a-z0-9-]+)::?before\s*$', sel)
        if name:
            icon_map[name.group(1)] = m.group(1)

brands_css = (pkg / 'css' / 'brands.css').read_text(encoding='utf8')
brand_names = set(re.findall(r'\.(fa-[a-z0-9-]+)::?before', brands_css))

missing = sorted(n for n in used if n not in icon_map)
if missing:
    print('warning: no glyph for', ', '.join(missing))

solid_cps, brand_cps, rules = set(extra_codepoints), set(), []
for name in sorted(used):
    if name not in icon_map:
        continue
    cp = icon_map[name]
    (brand_cps if name in brand_names else solid_cps).add(cp)
    rules.append(f'.{name}::before{{content:"\\{cp}"}}')


def make_subset(src, dest, cps):
    options = subset.Options()
    options.flavor = 'woff2'
    options.layout_features = ['*']
    options.notdef_outline = True
    font = subset.load_font(str(src), options)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=[int(c, 16) for c in cps])
    subsetter.subset(font)
    subset.save_font(font, str(dest), options)


make_subset(pkg / 'webfonts' / 'fa-solid-900.woff2', out / 'fa-solid-subset.woff2', solid_cps)
if brand_cps:
    make_subset(pkg / 'webfonts' / 'fa-brands-400.woff2', out / 'fa-brands-subset.woff2', brand_cps)

header = """/* Font Awesome Free 6.5.2 subset (icons: CC BY 4.0, fonts: SIL OFL 1.1, https://fontawesome.com/license/free).
   Generated by tools/build-icon-subset.py; do not edit by hand. */
@font-face{font-family:'Font Awesome 6 Free';font-style:normal;font-weight:900;font-display:block;src:url(fa-solid-subset.woff2) format('woff2')}
@font-face{font-family:'Font Awesome 6 Brands';font-style:normal;font-weight:400;font-display:block;src:url(fa-brands-subset.woff2) format('woff2')}
.fa-solid,.fas,.fa-brands,.fab{-moz-osx-font-smoothing:grayscale;-webkit-font-smoothing:antialiased;display:var(--fa-display,inline-block);font-style:normal;font-variant:normal;line-height:1;text-rendering:auto}
.fa-solid,.fas{font-family:'Font Awesome 6 Free';font-weight:900}
.fa-brands,.fab{font-family:'Font Awesome 6 Brands';font-weight:400}
"""
(out / 'icons.css').write_text(header + '\n'.join(rules) + '\n', encoding='utf8')
print(f'{len(rules)} icons · solid {len(solid_cps)} glyphs · brands {len(brand_cps)} glyphs')
